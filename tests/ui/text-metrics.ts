const SOFT_HYPHEN = '\u00ad';

function advanceOf(ch: string): number {
  if (ch === SOFT_HYPHEN) return 0;
  return ADVANCE[ch] ?? ADVANCE.M;
}

/** Kerning-free sum of advances, px at 12 px / 500 Geist. */
export function advanceSum(s: string): number {
  let total = 0;
  for (const ch of s) total += advanceOf(ch);
  return total;
}

/** Rendered width of `s` on one line, px at 12 px / 500 Geist (advances + pair kerning; the calibrated measure). */
export function width(s: string): number {
  const chars = [...s].filter((ch) => ch !== SOFT_HYPHEN);
  let total = 0;
  for (let i = 0; i < chars.length; i++) {
    total += advanceOf(chars[i]);
    if (i > 0) total += KERNING[chars[i - 1] + chars[i]] ?? 0;
  }
  return total;
}
